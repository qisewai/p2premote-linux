target("p2premote_minirtc_probe")
    set_kind("binary")
    set_default(false)
    set_targetdir(path.join(os.projectdir(), "../../minirtc-probe"))
    add_deps("minirtc")
    set_languages("c++20")
    add_defines("NOMINMAX", "UNICODE", "_UNICODE")
    add_syslinks("winmm", "user32", "gdi32")
    add_packages("libyuv")
    add_files(path.join(os.scriptdir(), "main.cpp"), path.join(os.scriptdir(), "desktop_probe.cpp"))
    local repo = path.absolute(path.join(os.scriptdir(), "../.."))
    add_files(path.join(repo, "core/src/desktop_input.cpp"), path.join(repo, "core/src/latency_trace.cpp"),
              path.join(repo, "proto/input_protocol.cpp"))
    add_includedirs(path.join(os.projectdir(), "src/api"), path.join(repo, "core/src"),
                    path.join(repo, "core/include"), path.join(repo, "proto/include"))
target_end()

